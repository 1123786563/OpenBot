// Render OpenBot's .env from Infisical, which is the source of truth.
// Edit a value in Infisical, then run `bun run sync:env` from the repository root and restart OpenBot.
// Usage: bun run sync:env [output-file]   default: the repository root .env
import { readFile, rename, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { parseEnv } from "node:util";
import { InfisicalSDK } from "@infisical/sdk";
import { mergeEnv, renderEnv } from "./infisical-env-file";

const projectRoot = resolve(import.meta.dir, "..");

const {
  INFISICAL_SITE_URL,
  INFISICAL_PROJECT_ID,
  INFISICAL_ENV = "dev",
  INFISICAL_CLIENT_ID,
  INFISICAL_CLIENT_SECRET,
} = process.env;
if (
  !INFISICAL_SITE_URL ||
  !INFISICAL_PROJECT_ID ||
  !INFISICAL_CLIENT_ID ||
  !INFISICAL_CLIENT_SECRET
) {
  throw new Error(
    "Run `bun run sync:env` from the repository root: it loads the machine identity",
  );
}
const out = resolve(process.argv[2] ?? join(projectRoot, ".env"));

const client = new InfisicalSDK({ siteUrl: INFISICAL_SITE_URL });
await client.auth().universalAuth.login({
  clientId: INFISICAL_CLIENT_ID,
  clientSecret: INFISICAL_CLIENT_SECRET,
});
// expandSecretReferences: false, so a value holding "$X" or backticks comes out as written.
// shortcut: secrets at the root path only, make this recursive once the project uses folders.
const { secrets } = await client.secrets().listSecrets({
  projectId: INFISICAL_PROJECT_ID,
  environment: INFISICAL_ENV,
  secretPath: "/",
  expandSecretReferences: false,
});
// A name that is not a variable name, such as "db.url", cannot be loaded.
const values = Object.fromEntries(
  secrets
    .filter((secret) => /^[A-Za-z_][A-Za-z0-9_]*$/.test(secret.secretKey))
    .map((secret) => [secret.secretKey, secret.secretValue]),
);
// Nothing below can leave a half-written or emptied file behind.
if (!Object.keys(values).length)
  throw new Error(
    `Infisical returned no secrets in ${INFISICAL_ENV}; ${out} left untouched`,
  );

const current = parseEnv(await readFile(out, "utf8").catch(() => ""));
// A filled-in value that only exists locally would be lost by the rewrite, unless start.sh wrote it.
const { values: merged, kept, localOnly: local } = mergeEnv(values, current);
if (local.length > 0) {
  throw new Error(
    `Only in ${out}, which is left untouched. Add them to Infisical first: ${local.join(", ")}`,
  );
}

const text = renderEnv(merged);
const carried = kept.length
  ? `\n# ${kept.join(", ")}: generated by scripts/start.sh and carried over. Infisical has none.`
  : "";
await writeFile(
  `${out}.tmp`,
  `# Generated by scripts/infisical-env.ts from Infisical. Edit there, not here.${carried}\n${text}\n`,
  {
    mode: 0o600,
  },
);
await rename(`${out}.tmp`, out);
console.log(`Wrote ${Object.keys(values).length} keys to ${out}`);
