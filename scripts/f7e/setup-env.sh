#!/usr/bin/env bash
# F7E — generate the isolated stack's env files with locally random secrets.
# Values are written with mode 600 and never printed. Re-running overwrites.
# Usage: bash scripts/f7e/setup-env.sh <main-checkout-env> <worktree-root>
set -euo pipefail
umask 077 # secret files are 600 from the first byte; no post-write chmod window
MAIN_ENV="${1:?main checkout .env}"
ROOT="${2:?worktree root}"
rand() { openssl rand -hex 24; }
# `|| true`: with -e/pipefail a missing key aborts inside the command
# substitution, before the friendly [ -n … ] checks below can name it.
pick() { grep -m1 "^$1=" "$MAIN_ENV" | sed 's/^[^=]*=//' | sed 's/^"//;s/"$//' || true ; }
# The 127.0.0.1:15434 Postgres is provisioned outside this script with the SAME
# openbot password the main checkout's DATABASE_URL carries — one source
# variable feeds both sides; it is never echoed.
PG_PASSWORD=$(pick DATABASE_URL | sed -E 's!^.*/[^:/]*:([^@]*)@.*$!\1!')

# --- opik compose env ---
cat > "$ROOT/.env.f7e-opik" <<E1
OPIK_MYSQL_ROOT_PASSWORD=$(rand)
OPIK_MYSQL_PASSWORD=$(rand)
OPIK_REDIS_PASSWORD=$(rand)
OPIK_CLICKHOUSE_PASSWORD=$(rand)
OPIK_MINIO_ROOT_USER=opikf7e$(openssl rand -hex 4)
OPIK_MINIO_ROOT_PASSWORD=$(rand)
OPIK_PORT=15175
OPIK_OTLP_HTTP_PORT=15419
OPIK_OTLP_GRPC_PORT=15420
E1
chmod 600 "$ROOT/.env.f7e-opik"

# --- server + langgraph env (stock phase; billing phase appends .env.f7e-billing) ---
OPENAI_API_KEY=$(pick OPENAI_API_KEY)
OPENAI_BASE_URL=$(pick OPENAI_BASE_URL)
[ -n "$OPENAI_API_KEY" ] || { echo "OPENAI_API_KEY missing in main env" >&2; exit 1; }
[ -n "$OPENAI_BASE_URL" ] || { echo "OPENAI_BASE_URL missing in main env" >&2; exit 1; }
# Shape-check, not just non-empty (R1-E-01): an unparsable DATABASE_URL (no
# user:pass segment, or the key missing entirely) falls through the sed
# unchanged, and the whole URL would silently become the password.
# Any "://", "@", or empty value takes the friendly-error path instead.
case "$PG_PASSWORD" in
  *"://"*|*"@"*|"")
    echo "DATABASE_URL in main env is missing or has no parsable postgres password segment (expected ...://user:pass@host...): the isolated stack's Postgres password is sourced from it" >&2
    exit 1
    ;;
esac
cat > "$ROOT/.env.f7e" <<E2
# generated by scripts/f7e/setup-env.sh — mode 600, git-ignored, never committed
DATABASE_URL=postgresql://openbot:${PG_PASSWORD}@127.0.0.1:15434/openbot
KEY_ENCRYPTION_KEY=$(rand)
PORT=13002
BETTER_AUTH_URL=http://localhost:13002
BETTER_AUTH_SECRET=$(rand)
TRUSTED_ORIGINS=http://localhost:13002,http://127.0.0.1:13002
CASDOOR_OAUTH_CLIENT_ID=PLACEHOLDER_CASDOOR_CLIENT_ID
CASDOOR_OAUTH_CLIENT_SECRET=PLACEHOLDER_CASDOOR_CLIENT_SECRET
CASDOOR_OAUTH_ISSUER=http://localhost:18001
OPIK_ENABLED=true
OPIK_BASE_URL=http://127.0.0.1:15175/api
OPIK_WORKSPACE_NAME=default
OTEL_EXPORTER_OTLP_ENDPOINT=http://127.0.0.1:15175/api/v1/private/otel
OTEL_SERVICE_NAME=openbot-f7e
OPENAI_API_KEY=${OPENAI_API_KEY}
OPENAI_BASE_URL=${OPENAI_BASE_URL}
BOT_MODEL=glm-4-flash
BOT_PROVIDER=openai
MANAGED_AGENT_TOKEN=$(rand)
E2
chmod 600 "$ROOT/.env.f7e"
echo "wrote $ROOT/.env.f7e{,-opik} (values redacted)"
