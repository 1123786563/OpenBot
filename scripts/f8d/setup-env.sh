#!/usr/bin/env bash
# F8D — generate the isolated stack's env files with locally random secrets.
#
# Values are written with mode 600 and never printed. Re-running overwrites.
#
# Usage: bash scripts/f8d/setup-env.sh <main-checkout-env> <worktree-root>
set -euo pipefail
umask 077 # secret files are 600 from the first byte; no post-write chmod window
MAIN_ENV="${1:?main checkout .env}"
ROOT="${2:?worktree root}"
rand() { openssl rand -hex 24; }
# `|| true`: with -e/pipefail a missing key aborts inside the command
# substitution, before the friendly [ -n … ] checks below can name it.
pick() { grep -m1 "^$1=" "$MAIN_ENV" | sed 's/^[^=]*=//' | sed 's/^"//;s/"$//' || true ; }
# The 127.0.0.1:15434 Postgres is provisioned outside this script with the SAME
# openbot password the main checkout's DATABASE_URL carries — one source
# variable feeds both sides; it is never echoed.
PG_PASSWORD=$(pick DATABASE_URL | sed -E 's!^.*/[^:/]*:([^@]*)@.*$!\1!')

OPENAI_API_KEY=$(pick OPENAI_API_KEY)
OPENAI_BASE_URL=$(pick OPENAI_BASE_URL)
[ -n "$OPENAI_API_KEY" ] || { echo "OPENAI_API_KEY missing in main env" >&2; exit 1; }
[ -n "$OPENAI_BASE_URL" ] || { echo "OPENAI_BASE_URL missing in main env" >&2; exit 1; }
[ -n "$PG_PASSWORD" ] || { echo "DATABASE_URL missing in main env: the isolated stack's Postgres password is sourced from it" >&2; exit 1; }

# --- opik compose env ---
cat > "$ROOT/.env.f8d-opik" <<E1
OPIK_MYSQL_ROOT_PASSWORD=$(rand)
OPIK_MYSQL_PASSWORD=$(rand)
OPIK_REDIS_PASSWORD=$(rand)
OPIK_CLICKHOUSE_PASSWORD=$(rand)
OPIK_MINIO_ROOT_USER=opikf8d$(openssl rand -hex 4)
OPIK_MINIO_ROOT_PASSWORD=$(rand)
OPIK_PORT=15175
OPIK_OTLP_HTTP_PORT=15419
OPIK_OTLP_GRPC_PORT=15420
E1
chmod 600 "$ROOT/.env.f8d-opik"

# --- server + langgraph base env (single billed configuration; stock phase not needed for F8D) ---
cat > "$ROOT/.env.f8d" <<E2
# generated by scripts/f8d/setup-env.sh — mode 600, git-ignored, never committed
DATABASE_URL=postgresql://openbot:${PG_PASSWORD}@127.0.0.1:15434/openbot
KEY_ENCRYPTION_KEY=$(openssl rand -base64 32 | tr -d '\n')
PORT=13002
BETTER_AUTH_URL=http://localhost:13002
BETTER_AUTH_SECRET=$(rand)
TRUSTED_ORIGINS=http://localhost:13002,http://127.0.0.1:13002
CASDOOR_OAUTH_CLIENT_ID=PLACEHOLDER_CASDOOR_CLIENT_ID
CASDOOR_OAUTH_CLIENT_SECRET=PLACEHOLDER_CASDOOR_CLIENT_SECRET
CASDOOR_OAUTH_ISSUER=http://localhost:18001
OPIK_ENABLED=true
OPIK_BASE_URL=http://127.0.0.1:15175/api
OPIK_WORKSPACE_NAME=default
OTEL_EXPORTER_OTLP_ENDPOINT=http://127.0.0.1:15175/api/v1/private/otel
OTEL_EXPORTER_OTLP_TRACES_ENDPOINT=http://127.0.0.1:15175/api/v1/private/otel/v1/traces
OTEL_SERVICE_NAME=openbot-f8d
OPENAI_API_KEY=${OPENAI_API_KEY}
OPENAI_BASE_URL=${OPENAI_BASE_URL}
BOT_MODEL=glm-4-flash
BOT_PROVIDER=openai
MANAGED_AGENT_TOKEN=$(rand)
INITIAL_ADMIN_EMAILS=admin@example.com
INTELLIGENCE_API_URL=http://127.0.0.1:13002
INTELLIGENCE_GATEWAY_WS_URL=ws://127.0.0.1:13002
INTELLIGENCE_API_KEY=$(rand)
AGENT_ENDPOINT_ALLOWED_HOSTS=127.0.0.1:14202,localhost:14202
E2
chmod 600 "$ROOT/.env.f8d"

# --- billed additions (credit machinery, remote budget contract, judge entrance, retention floor) ---
cat > "$ROOT/.env.f8d-billed" <<E3
# billed-phase additions — mode 600, git-ignored, never committed
LAGO_API_URL=http://127.0.0.1:48889
LAGO_API_KEY=$(rand)
BILLING_MODEL_CREDIT_RATES={"glm-4-flash":{"input":"0.000001","output":"0.000001"}}
BILLING_MODEL_MAX_RESERVATION_TOKENS={"glm-4-flash":{"input":200000,"output":200000}}
REMOTE_BUDGET_CONTRACT_ENDPOINTS=http://127.0.0.1:14202/ag-ui
MANAGED_AGENT_AG_UI_URL=http://127.0.0.1:14202/ag-ui
OPIK_JUDGE_ENTRANCES={"glm-flash":{"modelName":"glm-4-flash","apiKeyEnv":"OPENAI_API_KEY"}}
OPIK_RETENTION_RUNS_DAYS=1
OPIK_RETENTION_DATASETS_DAYS=1
OPIK_RETENTION_EXPERIMENTS_DAYS=1
OPIK_RETENTION_EXPORTS_DAYS=1
E3
chmod 600 "$ROOT/.env.f8d-billed"
echo "wrote $ROOT/.env.f8d{,-opik,-billed} (values redacted)"
