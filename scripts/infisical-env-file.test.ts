import { afterAll, expect, test } from "bun:test";
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { mergeEnv, planEnvFiles, renderEnv } from "./infisical-env-file";

const VALUES = {
  PLAIN: "postgres://u:p@h:5432/db,a=b-c",
  DOLLAR: "a$HOME.b`id`",
  HASH: "a#b",
  QUOTES: `a'"b`,
  MULTILINE: "first line\nsecond line",
  BACKSLASH: "a\\b",
  EMPTY: "",
};

// What OpenBot's own loader makes of the file, read back the way the server and scripts read it.
function reload(values: Record<string, string>): Record<string, string> {
  const file = join(tmpdir(), `env-file-${crypto.randomUUID()}`);
  writeFileSync(file, renderEnv(values));
  const env = JSON.parse(
    spawnSync(
      "bun",
      [`--env-file=${file}`, "-e", "console.log(JSON.stringify(process.env))"],
      {
        cwd: tmpdir(),
      },
    ).stdout.toString(),
  );
  return Object.fromEntries(Object.keys(values).map((key) => [key, env[key]]));
}

test("every value survives being loaded back by bun", () => {
  expect(reload(VALUES)).toEqual(VALUES);
});

test("a value with nothing to escape stays bare and the rest is quoted", () => {
  const lines = renderEnv({ PLAIN: VALUES.PLAIN, HASH: VALUES.HASH })
    .trimEnd()
    .split("\n");
  expect(lines[0]).toBe(`PLAIN=${VALUES.PLAIN}`);
  expect(lines[1]).toBe('HASH="a#b"');
});

test("a backslash beside a character that needs quoting is refused, not mangled", () => {
  expect(() => renderEnv({ KEY: "a\\b$c" })).toThrow("KEY holds a backslash");
});

test("a value only the local file has is carried over when start.sh wrote it and refused otherwise", () => {
  expect(
    mergeEnv(
      { OPENAI_API_KEY: "k", EMPTY: "" },
      {
        MANAGED_AGENT_TOKEN: "minted",
        OPENAI_API_KEY: "stale",
        EMPTY: "filled locally",
        LOCAL_ONLY: "x",
      },
    ),
  ).toEqual({
    values: { OPENAI_API_KEY: "k", EMPTY: "", MANAGED_AGENT_TOKEN: "minted" },
    kept: ["MANAGED_AGENT_TOKEN"],
    localOnly: ["LOCAL_ONLY"],
  });
  // Another file start.sh does not write: nothing is carried over.
  expect(mergeEnv({ A: "1" }, { MANAGED_AGENT_TOKEN: "minted" }, [])).toEqual({
    values: { A: "1" },
    kept: [],
    localOnly: ["MANAGED_AGENT_TOKEN"],
  });
});

const FOLDERS = {
  "/": { DATABASE_URL: "postgres://d" },
  "/server": { KEY_ENCRYPTION_KEY: "k" },
  "/worker": { FLEXPRICE_URL: "https://flexprice.example" },
  "/agents": { AGENT_BOT_MODEL: "m", OPENAI_API_KEY: "a" },
};

test("each Infisical folder becomes its service's file, and nothing is copied between them", () => {
  const plans = planEnvFiles(FOLDERS, (file) =>
    file === "deploy/agents/.env" ? { MANAGED_AGENT_TOKEN: "minted" } : {},
  );
  expect(plans.map(({ file, localOnly }) => [file, localOnly])).toEqual([
    ["deploy/openbot/.env", []],
    ["deploy/openbot/.env.server", []],
    ["deploy/openbot/.env.worker", []],
    ["deploy/agents/.env", []],
  ]);
  expect(plans.map(({ text }) => text)).toEqual([
    "# Generated by scripts/infisical-env.ts from Infisical /. Edit there, not here.\nDATABASE_URL=postgres://d\n",
    "# Generated by scripts/infisical-env.ts from Infisical /server. Edit there, not here.\nKEY_ENCRYPTION_KEY=k\n",
    "# Generated by scripts/infisical-env.ts from Infisical /worker. Edit there, not here.\nFLEXPRICE_URL=https://flexprice.example\n",
    "# Generated by scripts/infisical-env.ts from Infisical /agents. Edit there, not here.\n" +
      "# MANAGED_AGENT_TOKEN: generated by scripts/start.sh and carried over. Infisical has none.\n" +
      "AGENT_BOT_MODEL=m\nOPENAI_API_KEY=a\nMANAGED_AGENT_TOKEN=minted\n",
  ]);
});

test("a key the server would read twice, because it is in two of its folders, is refused", () => {
  // The worker's folder is none of the server's business.
  expect(() =>
    planEnvFiles(
      {
        ...FOLDERS,
        "/worker": {
          ...FOLDERS["/worker"],
          OPENAI_API_KEY: "the worker's own",
        },
      },
      () => ({}),
    ),
  ).not.toThrow();
  expect(() =>
    planEnvFiles(
      {
        ...FOLDERS,
        "/server": { ...FOLDERS["/server"], OPENAI_API_KEY: "a second home" },
      },
      () => ({}),
    ),
  ).toThrow(
    "OPENAI_API_KEY is in both /server and /agents in Infisical, and the server reads both. Keep it in one.",
  );
});

// The sync script itself, run against a stand-in Infisical that answers the two routes the SDK calls.
const SECRETS: Record<string, { secretKey: string; secretValue: string }[]> = {
  "/": [
    { secretKey: "DATABASE_URL", secretValue: "postgres://d" },
    { secretKey: "db.url", secretValue: "not-a-variable" },
  ],
  "/server": [{ secretKey: "KEY_ENCRYPTION_KEY", secretValue: "k" }],
  "/worker": [
    { secretKey: "FLEXPRICE_URL", secretValue: "https://flexprice.example" },
  ],
  "/agents": [{ secretKey: "OPENAI_API_KEY", secretValue: "a" }],
};
const standIn = Bun.serve({
  port: 0,
  fetch: async (request) => {
    const url = new URL(request.url);
    if (url.pathname === "/api/v1/auth/universal-auth/login")
      return Response.json({
        accessToken: "access-token",
        tokenType: "Bearer",
        expiresIn: 3600,
      });
    const path = url.searchParams.get("secretPath") ?? "";
    // As Infisical does for a folder nobody has created yet.
    if (!(path in SECRETS))
      return Response.json(
        { message: `Folder '${path}' not found` },
        { status: 404 },
      );
    return Response.json({ secrets: SECRETS[path as keyof typeof SECRETS] });
  },
});
const written: string[] = [];
afterAll(() => {
  standIn.stop(true);
  for (const file of written) rmSync(file, { recursive: true, force: true });
});

// A fresh repository root holding `before` (file → contents), after `sync:env` ran against the stand-in.
async function sync(before: Record<string, string>): Promise<{
  status: number;
  stderr: string;
  files: Record<string, string | null>;
}> {
  const root = join(tmpdir(), `env-sync-${crypto.randomUUID()}`);
  written.push(root);
  for (const [file, text] of Object.entries(before)) {
    mkdirSync(join(root, file, ".."), { recursive: true });
    writeFileSync(join(root, file), text);
  }
  const child = Bun.spawn(
    ["bun", resolve(import.meta.dir, "infisical-env.ts"), root],
    {
      cwd: tmpdir(),
      env: {
        PATH: process.env.PATH,
        HOME: process.env.HOME,
        INFISICAL_SITE_URL: `http://127.0.0.1:${standIn.port}`,
        INFISICAL_PROJECT_ID: "project",
        INFISICAL_CLIENT_ID: "identity",
        INFISICAL_CLIENT_SECRET: "secret",
      },
      stdout: "pipe",
      stderr: "pipe",
    },
  );
  // Spawned asynchronously: a synchronous spawn would hold this process still, and the stand-in runs inside it.
  const [stderr, status] = await Promise.all([
    new Response(child.stderr).text(),
    child.exited,
  ]);
  const files = Object.fromEntries(
    [
      "deploy/openbot/.env",
      "deploy/openbot/.env.server",
      "deploy/openbot/.env.worker",
      "deploy/agents/.env",
    ].map((file) => {
      try {
        return [file, readFileSync(join(root, file), "utf8")];
      } catch {
        return [file, null];
      }
    }),
  );
  return { status, stderr, files };
}

test("a sync writes one file per Infisical folder, copying nothing between them, and carries over the secrets start.sh generated", async () => {
  const { status, stderr, files } = await sync({
    "deploy/agents/.env": "MANAGED_AGENT_TOKEN=minted\nAGENT_TOOL_TOKEN=\n",
  });
  expect(status, stderr).toBe(0);
  expect(files).toEqual({
    "deploy/openbot/.env":
      "# Generated by scripts/infisical-env.ts from Infisical /. Edit there, not here.\nDATABASE_URL=postgres://d\n",
    "deploy/openbot/.env.server":
      "# Generated by scripts/infisical-env.ts from Infisical /server. Edit there, not here.\nKEY_ENCRYPTION_KEY=k\n",
    "deploy/openbot/.env.worker":
      "# Generated by scripts/infisical-env.ts from Infisical /worker. Edit there, not here.\nFLEXPRICE_URL=https://flexprice.example\n",
    "deploy/agents/.env":
      "# Generated by scripts/infisical-env.ts from Infisical /agents. Edit there, not here.\n" +
      "# MANAGED_AGENT_TOKEN: generated by scripts/start.sh and carried over. Infisical has none.\n" +
      "OPENAI_API_KEY=a\nMANAGED_AGENT_TOKEN=minted\n",
  });
});

test("until the service folders exist, every key sits in `/` and goes into the deployment's file", async () => {
  const folders = structuredClone(SECRETS);
  for (const path of Object.keys(folders))
    delete SECRETS[path as keyof typeof SECRETS];
  SECRETS["/"] = [
    { secretKey: "DATABASE_URL", secretValue: "postgres://d" },
    { secretKey: "KEY_ENCRYPTION_KEY", secretValue: "k" },
  ];
  try {
    const { status, stderr, files } = await sync({});
    expect(status, stderr).toBe(0);
    expect(files["deploy/openbot/.env"]).toBe(
      "# Generated by scripts/infisical-env.ts from Infisical /. Edit there, not here.\nDATABASE_URL=postgres://d\nKEY_ENCRYPTION_KEY=k\n",
    );
    // The service files exist, each saying where it comes from, and hold nothing yet.
    for (const [file, folder] of [
      ["deploy/openbot/.env.server", "/server"],
      ["deploy/openbot/.env.worker", "/worker"],
      ["deploy/agents/.env", "/agents"],
    ])
      expect(files[file]).toBe(
        `# Generated by scripts/infisical-env.ts from Infisical ${folder}. Edit there, not here.\n`,
      );
  } finally {
    Object.assign(SECRETS, folders);
  }
});

test("a sync is refused and every file left as it was when one holds a value Infisical lacks", async () => {
  const before = {
    "deploy/openbot/.env": "DATABASE_URL=stale\n",
    "deploy/openbot/.env.server": "EDITED_BY_HAND=1\n",
  };
  const { status, stderr, files } = await sync(before);
  expect(status, stderr).toBe(1);
  expect(stderr).toContain(
    "Add them to Infisical first: deploy/openbot/.env.server: EDITED_BY_HAND",
  );
  expect(files).toEqual({
    ...before,
    "deploy/openbot/.env.worker": null,
    "deploy/agents/.env": null,
  });
});
