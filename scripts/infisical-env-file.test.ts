import { spawnSync } from "node:child_process";
import { readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { afterAll, expect, test } from "bun:test";
import { mergeEnv, renderEnv } from "./infisical-env-file";

const VALUES = {
  PLAIN: "postgres://u:p@h:5432/db,a=b-c",
  DOLLAR: "a$HOME.b`id`",
  HASH: "a#b",
  QUOTES: `a'"b`,
  MULTILINE: "first line\nsecond line",
  BACKSLASH: "a\\b",
  EMPTY: "",
};

// What OpenBot's own loader makes of the file, read back the way the server and scripts read it.
function reload(values: Record<string, string>): Record<string, string> {
  const file = join(tmpdir(), `env-file-${crypto.randomUUID()}`);
  writeFileSync(file, renderEnv(values));
  const env = JSON.parse(
    spawnSync(
      "bun",
      [`--env-file=${file}`, "-e", "console.log(JSON.stringify(process.env))"],
      {
        cwd: tmpdir(),
      },
    ).stdout.toString(),
  );
  return Object.fromEntries(Object.keys(values).map((key) => [key, env[key]]));
}

test("every value survives being loaded back by bun", () => {
  expect(reload(VALUES)).toEqual(VALUES);
});

test("a value with nothing to escape stays bare and the rest is quoted", () => {
  const lines = renderEnv({ PLAIN: VALUES.PLAIN, HASH: VALUES.HASH })
    .trimEnd()
    .split("\n");
  expect(lines[0]).toBe(`PLAIN=${VALUES.PLAIN}`);
  expect(lines[1]).toBe('HASH="a#b"');
});

test("a backslash beside a character that needs quoting is refused, not mangled", () => {
  expect(() => renderEnv({ KEY: "a\\b$c" })).toThrow("KEY holds a backslash");
});

test("a sync keeps the secrets start.sh generated and refuses any other value only .env has", () => {
  const infisical = { OPENAI_API_KEY: "k", EMPTY: "" };
  expect(
    mergeEnv(infisical, {
      MANAGED_AGENT_TOKEN: "minted",
      OPENAI_API_KEY: "stale",
      EMPTY: "filled locally",
      LOCAL_ONLY: "x",
    }),
  ).toEqual({
    values: { OPENAI_API_KEY: "k", EMPTY: "", MANAGED_AGENT_TOKEN: "minted" },
    kept: ["MANAGED_AGENT_TOKEN"],
    localOnly: ["LOCAL_ONLY"],
  });
  expect(mergeEnv(infisical, { AGENT_TOOL_TOKEN: "" })).toEqual({
    values: infisical,
    kept: [],
    localOnly: [],
  });
});

// The sync script itself, run against a stand-in Infisical that answers the two routes the SDK calls.
const standIn = Bun.serve({
  port: 0,
  fetch: async (request) => {
    if (new URL(request.url).pathname === "/api/v1/auth/universal-auth/login")
      return Response.json({
        accessToken: "access-token",
        tokenType: "Bearer",
        expiresIn: 3600,
      });
    return Response.json({
      secrets: [{ secretKey: "OPENAI_API_KEY", secretValue: "k" }],
    });
  },
});
const written: string[] = [];
afterAll(() => {
  standIn.stop(true);
  for (const file of written) rmSync(file, { force: true });
});

// Spawned asynchronously: a synchronous spawn would hold this process still, and the stand-in runs inside it.
async function sync(
  dotEnv: string,
): Promise<{ status: number; stderr: string; text: string }> {
  const file = join(tmpdir(), `env-sync-${crypto.randomUUID()}`);
  written.push(file);
  writeFileSync(file, dotEnv);
  const child = Bun.spawn(
    ["bun", resolve(import.meta.dir, "infisical-env.ts"), file],
    {
      cwd: tmpdir(),
      env: {
        PATH: process.env.PATH,
        HOME: process.env.HOME,
        INFISICAL_SITE_URL: `http://127.0.0.1:${standIn.port}`,
        INFISICAL_PROJECT_ID: "project",
        INFISICAL_CLIENT_ID: "identity",
        INFISICAL_CLIENT_SECRET: "secret",
      },
      stdout: "pipe",
      stderr: "pipe",
    },
  );
  const [stderr, status] = await Promise.all([
    new Response(child.stderr).text(),
    child.exited,
  ]);
  return { status, stderr, text: readFileSync(file, "utf8") };
}

test("a sync carries over the secrets start.sh generated", async () => {
  const { status, text } = await sync(
    "MANAGED_AGENT_TOKEN=minted\nAGENT_TOOL_TOKEN=\n",
  );
  expect(status).toBe(0);
  expect(text).toBe(
    "# Generated by scripts/infisical-env.ts from Infisical. Edit there, not here.\n" +
      "# MANAGED_AGENT_TOKEN: generated by scripts/start.sh and carried over. Infisical has none.\n" +
      "OPENAI_API_KEY=k\nMANAGED_AGENT_TOKEN=minted\n",
  );
});

test("a sync is refused, the file untouched, when .env holds another value Infisical lacks", async () => {
  const dotEnv = "OPENAI_API_KEY=stale\nEDITED_BY_HAND=1\n";
  const { status, stderr, text } = await sync(dotEnv);
  expect(status).toBe(1);
  expect(stderr).toContain("Add them to Infisical first: EDITED_BY_HAND");
  expect(text).toBe(dotEnv);
});
