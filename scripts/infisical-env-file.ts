import { ENV_FILES } from "../shared/env-files";

// The two readers of this file disagree: `bun --env-file` and Compose's env_file both expand "$",
// even inside single quotes, and read backslashes inside quotes differently. A bare value comes
// back as written unless it holds one of these; a quoted one cannot carry a backslash at all.
const NEEDS_QUOTES = /[$#\r\n]/;

export function renderEnv(values: Record<string, string>): string {
  return Object.entries(values)
    .map(([key, value]) => {
      if (!NEEDS_QUOTES.test(value)) return `${key}=${value}`;
      if (value.includes("\\")) {
        throw new Error(
          `${key} holds a backslash and "$", "#" or a line break, which no .env spelling survives`,
        );
      }
      const quoted = value
        .replaceAll("$", "\\$")
        .replaceAll('"', '\\"')
        .replaceAll("\n", "\\n");
      return `${key}="${quoted}"`;
    })
    .join("\n");
}

/** `scripts/start.sh` mints these on a first run and writes them into the agents' file: the machine identity is read-only, so they cannot go to Infisical from there. */
export const START_SH_KEYS = ["AGENT_TOOL_TOKEN", "MANAGED_AGENT_TOKEN"];

/**
 * The folders each process reads: a key in two of them would reach that process twice, with nothing
 * to say which value it meant.
 */
const READ_TOGETHER = [
  { process: "server", folders: ["/", "/server", "/agents"] },
  { process: "worker", folders: ["/", "/server", "/worker"] },
];

/**
 * What each service's file is to hold: its Infisical folder's values, then the ones only the local
 * file has that start.sh wrote. `localOnly` lists the other filled-in values a rewrite would lose.
 */
export function planEnvFiles(
  folders: Record<string, Record<string, string>>,
  current: (file: string) => Record<string, string>,
): { file: string; text: string; localOnly: string[] }[] {
  const home = new Map<string, string>();
  for (const { process, folders: together } of READ_TOGETHER) {
    for (const folder of together)
      for (const key of Object.keys(folders[folder] ?? {})) {
        const first = home.get(key);
        if (first)
          throw new Error(
            `${key} is in both ${first} and ${folder} in Infisical, and the ${process} reads both. Keep it in one.`,
          );
        home.set(key, folder);
      }
    home.clear();
  }
  return ENV_FILES.map(({ folder, file, service }) => {
    const { values, kept, localOnly } = mergeEnv(
      folders[folder] ?? {},
      current(file),
      service === "agents" ? START_SH_KEYS : [],
    );
    const carried = kept.length
      ? `\n# ${kept.join(", ")}: generated by scripts/start.sh and carried over. Infisical has none.`
      : "";
    const body = renderEnv(values);
    return {
      file,
      // No blank second line when the folder is empty.
      text: `# Generated by scripts/infisical-env.ts from Infisical ${folder}. Edit there, not here.${carried}\n${body ? `${body}\n` : ""}`,
      localOnly,
    };
  });
}

/**
 * What a rewrite of a file is to hold: Infisical's values, then the ones only the local file has that
 * start.sh wrote (`startShKeys`). `localOnly` are the other filled-in values a rewrite would lose.
 */
export function mergeEnv(
  infisical: Record<string, string>,
  current: Record<string, string>,
  startShKeys: readonly string[] = START_SH_KEYS,
): { values: Record<string, string>; kept: string[]; localOnly: string[] } {
  const carried: Record<string, string> = {};
  const kept: string[] = [];
  const localOnly: string[] = [];
  for (const [key, value] of Object.entries(current)) {
    if (!value || key in infisical) continue;
    if (startShKeys.includes(key)) {
      carried[key] = value;
      kept.push(key);
    } else localOnly.push(key);
  }
  return { values: { ...infisical, ...carried }, kept, localOnly };
}
