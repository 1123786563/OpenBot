/**
 * MT143 (Issue #186): the A1–A13 acceptance map — every acceptance item of the
 * parent spec bound to the evidence that exists in this tree, as a versioned
 * ledger full-coverage.test.ts verifies (files exist, suites are registered in
 * the e2e manifest, statuses are honest).
 *
 * Evidence kinds:
 *   coverage-suite — a coverage-*.test.ts whose matrix run proves both sides
 *                    of its planned entrances (server, restricted roles).
 *   suite          — any other real suite in the tree (chain or client side).
 *   report         — a generated artifact under reports/ (regenerated by
 *                    running the named command; never trusted blindly).
 *   record         — a review/evidence document delivered with the closure
 *                    batch (MT142 review records, MT141 gap census).
 */

export type EvidenceKind = "coverage-suite" | "suite" | "report" | "record";

export interface AcceptanceEvidence {
  readonly kind: EvidenceKind;
  /** A file path in the repo (suites/records) or worktree (reports). */
  readonly path: string;
  readonly pins: string;
}

