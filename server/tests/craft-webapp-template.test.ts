import { fileURLToPath } from "node:url";
import { describe, expect, test } from "../../tests/support/e2e-compat";
import { readFile } from "node:fs/promises";
import { dirname, join } from "node:path";

const herePath = fileURLToPath(import.meta.url);
const hereDir = dirname(herePath);

/**
 * THE SCAFFOLD'S CONTRACT WITH THE CODE IT GENERATES. (#364 spec D6 + F-2/#365)
 *
 * The preview serves every session's app on its OWN preview origin (#362's
 * host routing), in two shapes: the dev form under a PATH LABEL
 * (`http://127.0.0.1:<port>/<label>`, D5) and the production host form at the
 * origin's root (`<label>.<preview-base>`, D3/D7). The app cannot guess which
 * — so the session's start script injects `ONYX_WEBAPP_BASE_PATH=/<label>`
 * for the dev form (and nothing for the host form), and the scaffold mirrors
 * that ONE env into Next's URL machinery (`basePath`/`assetPrefix`) and into
 * client code (`NEXT_PUBLIC_BASE_PATH` via the `env` field, read by
 * `lib/base-path.ts`). No env → root path, the production behavior unchanged.
 *
 * What stays retired from #364 is the GUESSWORK half: no `resolveWebappBasePath`
 * cwd sniff, no session-id-in-cwd regex, no `/` → prefix redirects. The env is
 * injected by the controlled start side (start-webapp.sh, generated by the
 * server), never derived from where the process happens to run.
 *
 * These tests pin that split against the shipped template files so neither
 * half can silently come back (the HMR seam's pin lives in
 * craft-webapp-hmr.test.ts).
 */

const TEMPLATE = join(hereDir, "../assets/craft/web-template");

const read = (rel: string) => readFile(join(TEMPLATE, rel), "utf8");

/**
 * Evaluate a template module in a child process with a pinned env — the same
 * evaluation shape `next dev` performs (module-level `process.env` reads), so
 * the tests exercise the real env→config contract rather than re-deriving it.
 *
 * The capturing variant also records `console.warn` calls made DURING the
 * module evaluation (fix-ocr17): a present-but-malformed ONYX_WEBAPP_BASE_PATH
 * must not fall back to the root shape SILENTLY — the preview proxy keeps
 * addressing /<label>, so a silent fallback is a whole-origin 404 with nothing
 * in any log. The warning is the one observable trace such a misconfiguration
 * leaves, so the contract pins it alongside the fallback itself.
 */
async function evaluateModule<T>(
  rel: string,
  expression: string,
  env: Record<string, string>,
): Promise<T> {
  const { result } = await evaluateModuleCapturing<T>(rel, expression, env);
  return result;
}

async function evaluateModuleCapturing<T>(
  rel: string,
  expression: string,
  env: Record<string, string>,
): Promise<{ result: T; warnings: string[] }> {
  const proc = Bun.spawn(
    [
      process.execPath,
      "-e",
      `globalThis.__warns = [];
       console.warn = (...args) => {
         globalThis.__warns.push(args.map(String).join(" "));
       };
       import(process.argv[1]).then((m) =>
         console.log(JSON.stringify({ result: (${expression})(m), warnings: globalThis.__warns })),
       );`,
      join(TEMPLATE, rel),
    ],
    {
      env: { ...process.env, ...env },
      stdout: "pipe",
      stderr: "pipe",
    },
  );
  const [stdout, stderr, exitCode] = await Promise.all([
    new Response(proc.stdout).text(),
    new Response(proc.stderr).text(),
    proc.exited,
  ]);
  if (exitCode !== 0) {
    throw new Error(`module evaluation failed: ${stderr}`);
  }
  return JSON.parse(stdout) as { result: T; warnings: string[] };
}

describe("next.config.ts — the explicit env basePath (F-2, #365)", () => {
  test("ONYX_WEBAPP_BASE_PATH set → basePath + assetPrefix + inlined NEXT_PUBLIC_BASE_PATH", async () => {
    const config = await evaluateModule<Record<string, unknown>>(
      "next.config.ts",
      "(m) => m.default",
      { ONYX_WEBAPP_BASE_PATH: "/abc123label" },
    );
    expect(config.basePath).toBe("/abc123label");
    expect(config.assetPrefix).toBe("/abc123label");
    expect(config.env).toEqual({ NEXT_PUBLIC_BASE_PATH: "/abc123label" });
  });

  test("env unset or blank → root path, the production shape unchanged", async () => {
    for (const value of [undefined, "", "   "]) {
      const env: Record<string, string> = {};
      if (value !== undefined) env.ONYX_WEBAPP_BASE_PATH = value;
      const config = await evaluateModule<Record<string, unknown>>(
        "next.config.ts",
        "(m) => m.default",
        env,
      );
      expect(config.basePath).toBeUndefined();
      expect(config.assetPrefix).toBeUndefined();
      // Always set ("" in the root shape) so a stale env from a previous
      // dev-form boot can never leak a dead prefix into client code.
      expect(config.env).toEqual({ NEXT_PUBLIC_BASE_PATH: "" });
    }
  });

  test("a malformed env value falls back to the root-path shape (consumer-side whitelist, fix-ocr12)", async () => {
    // The injection side's whitelist (nextjs-dev.ts WEBAPP_BASE_PATH_PATTERN)
    // only governs what the controlled start script exports; a manual export
    // or an app-owned .env reaches next.config.ts unfiltered. A missing
    // leading slash crashes `next dev` outright; a trailing slash or a stray
    // character silently mis-mounts every asset URL. The template is its own
    // last line: anything outside the /<label> shape degrades to "" — the
    // same fallback, the same pattern, the same root-path production shape.
    // fix-ocr19 #5: UPPERCASE is outside that shape too — fix-ocr17 #3
    // dropped the pattern's `i` flag on the injection side (nextjs-dev.ts,
    // the minter only ever mints lowercase hex) but left it here; the
    // template side drops it in lockstep, so `/ABC123` falls back to the
    // root shape like any other malformed value.
    for (const value of ["label", "/x/", "/x!", "/ABC123"]) {
      const config = await evaluateModule<Record<string, unknown>>(
        "next.config.ts",
        "(m) => m.default",
        { ONYX_WEBAPP_BASE_PATH: value },
      );
      expect(config.basePath).toBeUndefined();
      expect(config.assetPrefix).toBeUndefined();
      expect(config.env).toEqual({ NEXT_PUBLIC_BASE_PATH: "" });
    }
  });

  test("a bare '/' mount falls back to the root-path shape too (fix-ocr15)", async () => {
    // fix-ocr15: `/` matched the old `{0,64}` quantifier — a label of ZERO
    // characters — and produced basePath:"/". Every resource URL the app
    // emits then starts with `//`, which URL grammar reads as a
    // PROTOCOL-RELATIVE address: `//api/tasks` escapes this origin entirely.
    // A mount needs at least one label character: `/` is the root shape's
    // spelling of "no mount", so it degrades to "" exactly like the other
    // malformed values.
    const config = await evaluateModule<Record<string, unknown>>(
      "next.config.ts",
      "(m) => m.default",
      { ONYX_WEBAPP_BASE_PATH: "/" },
    );
    expect(config.basePath).toBeUndefined();
    expect(config.assetPrefix).toBeUndefined();
    expect(config.env).toEqual({ NEXT_PUBLIC_BASE_PATH: "" });
  });

  test("a present-but-malformed value WARNS before falling back to the root shape (fix-ocr17)", async () => {
    // The fallback itself is pinned above; this pins its OBSERVABILITY. The
    // preview proxy addresses the app at /<label> — when the value exists but
    // is malformed, the silent root fallback used to leave a whole-origin 404
    // with nothing in any log. The misconfigured RAW value and the adopted
    // root form must both be named on stderr.
    const { result, warnings } = await evaluateModuleCapturing<
      Record<string, unknown>
    >("next.config.ts", "(m) => m.default", { ONYX_WEBAPP_BASE_PATH: "/x!" });
    expect(result.basePath).toBeUndefined();
    expect(result.assetPrefix).toBeUndefined();
    expect(result.env).toEqual({ NEXT_PUBLIC_BASE_PATH: "" });
    expect(warnings).toBeArrayOfSize(1);
    expect(warnings[0]).toContain("/x!"); // the value as received
    expect(warnings[0]).toContain("root"); // the shape that was adopted
  });

  test("an unset (or blank) env stays silent — the production shape never warns (fix-ocr17)", async () => {
    for (const env of [{}, { ONYX_WEBAPP_BASE_PATH: "" }]) {
      const { warnings } = await evaluateModuleCapturing<
        Record<string, unknown>
      >("next.config.ts", "(m) => m.default", env);
      expect(warnings).toBeArrayOfSize(0);
    }
  });

  test("no guesswork: the cwd sniff, the session-id regex and the redirects stay retired", async () => {
    const source = await read("next.config.ts");
    // #364 retired the cwd-derived mount (spec D6); #365 restores only the
    // EXPLICIT env half. Any of these resurfacing would re-teach the scaffold
    // to guess a mount from where it runs — the foot-gun the review killed.
    expect(source).not.toContain("resolveWebappBasePath");
    expect(source).not.toContain("process.cwd()");
    expect(source).not.toContain("redirects");
    expect(source).not.toContain("/api/craft/sessions");
  });

  test("keeps the HMR relay's allowed dev origins", async () => {
    const source = await read("next.config.ts");
    // The preview's HMR websocket is relayed by the API server dialing the
    // sandbox host; without these entries Next 16 blocks /_next/webpack-hmr
    // cross-origin and live reload dies silently (see craft-webapp-hmr.test.ts).
    expect(source).toContain("allowedDevOrigins");
    expect(source).toContain("127.0.0.1");
    expect(source).toContain("localhost");
  });
});

describe("lib/base-path.ts — the client-side face of the mount", () => {
  test("NEXT_PUBLIC_BASE_PATH inlined by next.config's env field prefixes apiUrl", async () => {
    const evaluated = await evaluateModule<{
      BASE_PATH: string;
      withSlash: string;
      withoutSlash: string;
    }>(
      "lib/base-path.ts",
      "(m) => ({ BASE_PATH: m.BASE_PATH, withSlash: m.apiUrl('/api/tasks'), withoutSlash: m.apiUrl('api/tasks') })",
      {
        NEXT_PUBLIC_BASE_PATH: "/abc123label",
      },
    );
    expect(evaluated.BASE_PATH).toBe("/abc123label");
    expect(evaluated.withSlash).toBe("/abc123label/api/tasks");
    expect(evaluated.withoutSlash).toBe("/abc123label/api/tasks");
  });

  test("no env → BASE_PATH is the empty string and apiUrl is the identity (production unchanged)", async () => {
    const module = await import(join(TEMPLATE, "lib/base-path.ts"));
    expect(module.BASE_PATH).toBe("");
    expect(module.apiUrl("/api/tasks")).toBe("/api/tasks");
    expect(module.apiUrl("api/tasks")).toBe("/api/tasks");
    expect(module.apiUrl("/api/tasks")).not.toContain("undefined");
  });

  test("fix-ocr22 #4: a shell-residue NEXT_PUBLIC_BASE_PATH outside the whitelist folds to ''", async () => {
    // lib/base-path.ts reads the env directly; next.config.ts's `env` field
    // normally inlines a sanitized value, but a manual export or an app-owned
    // .env reaches this module unfiltered — the same consumer-side exposure
    // fix-ocr12 closed for next.config.ts. The module therefore applies the
    // SAME whitelist as next.config.ts: anything outside the /<label> shape
    // (case-sensitive, ≥1 char) folds to the empty prefix, so a stale shell
    // value can never prefix every apiUrl() with a broken mount.
    for (const value of [
      "/x!",
      "/ABC123", // case-sensitive, in lockstep with next.config.ts
      "/", // the bare root spelling of "no mount" (fix-ocr15's verdict)
      "label", // missing the leading slash
      "/a_b", // underscore is outside the alphabet
      `/${"a".repeat(65)}`, // one past the 64-char bound
    ]) {
      const evaluated = await evaluateModule<{
        BASE_PATH: string;
        prefixed: string;
      }>(
        "lib/base-path.ts",
        "(m) => ({ BASE_PATH: m.BASE_PATH, prefixed: m.apiUrl('/api/tasks') })",
        { NEXT_PUBLIC_BASE_PATH: value },
      );
      expect(evaluated.BASE_PATH).toBe("");
      expect(evaluated.prefixed).toBe("/api/tasks");
    }
  });

  test("fix-ocr25 #4: a whitespace-padded value trims before the whitelist — the same verdict as next.config.ts", async () => {
    // 两个孪生防御（next.config.ts、nextjs-dev.ts）都先 trim 再校验；本模块
    // 是唯一未过滤的入口（手工 export、app-owned .env），却曾拿原始值直接
    // 过白名单 —— " /label " 在这里折叠为空前缀，而同值落在
    // ONYX_WEBAPP_BASE_PATH 上会挂载 /label：basePath 与 BASE_PATH 不一致，
    // 裸 fetch() 不带前缀的窗口。补齐 trim，两侧同判。
    const config = await evaluateModule<Record<string, unknown>>(
      "next.config.ts",
      "(m) => m.default",
      { ONYX_WEBAPP_BASE_PATH: " /label " },
    );
    // The twin's verdict first: trim → valid label → mounts.
    expect(config.basePath).toBe("/label");
    const evaluated = await evaluateModule<{ BASE_PATH: string }>(
      "lib/base-path.ts",
      "(m) => ({ BASE_PATH: m.BASE_PATH })",
      { NEXT_PUBLIC_BASE_PATH: " /label " },
    );
    // Same value, same verdict — the mismatch window is closed. RED: this
    // module used to fold the raw (untrimmed) value to "".
    expect(evaluated.BASE_PATH).toBe("/label");
  });

  test("fix-ocr25 #4: a whitespace-only value still folds to '' (pinned)", async () => {
    // 两侧同判非法→折叠 ""：trim 后为空，白名单照旧拒绝 —— 根形态。
    const evaluated = await evaluateModule<{ BASE_PATH: string }>(
      "lib/base-path.ts",
      "(m) => ({ BASE_PATH: m.BASE_PATH })",
      { NEXT_PUBLIC_BASE_PATH: "   " },
    );
    expect(evaluated.BASE_PATH).toBe("");
  });
});

// ── fix-ocr22 #11: the whitelist's parity lock ────────────────────────────────
//
// The /<label> whitelist now lives in THREE hand-synced copies: the server's
// injection-side WEBAPP_BASE_PATH_PATTERN (nextjs-dev.ts), the template's
// consumer-side regex in next.config.ts (fix-ocr12), and — since fix-ocr22 #4
// — the same regex in lib/base-path.ts. All three were verbatim copies with
// no synchronization lock: a one-sided tightening (or relaxation) would split
// the verdict on some input the other faces accept, and nothing would fail.
// This lock extracts each regex literal FROM ITS SOURCE and asserts the same
// boundary set (legal label, bare /, uppercase, overlong, illegal char, empty)
// is accepted/rejected IDENTICALLY on all three faces. Extraction failing
// (a rewritten literal, a renamed constant) fails too — the lock must not be
// able to rot into silence.
describe("whitelist parity lock (fix-ocr22 #11): one pattern, three copies, zero drift", () => {
  /** Pull a regex literal out of a source file by an anchor, flags and all. */
  function extractLiteral(
    source: string,
    anchor: RegExp,
    what: string,
  ): RegExp {
    const match = anchor.exec(source);
    if (!match) {
      throw new Error(`parity lock: could not locate ${what} in its source`);
    }
    const literal = match[1] as string;
    const lastSlash = literal.lastIndexOf("/");
    return new RegExp(
      literal.slice(1, lastSlash),
      literal.slice(lastSlash + 1),
    );
  }

  /** The shared boundary set: [value, every face must agree accept/reject]. */
  const boundaryValues: Array<[string, boolean]> = [
    ["/abc123", true], // the minted shape
    ["/a", true], // one-char label (the minimum)
    ["/label-with-dash-0", true], // dashes ride the alphabet
    [`/${"a".repeat(64)}`, true], // the 64-char upper bound
    [`/${"a".repeat(65)}`, false], // one past the bound (fix-ocr12's bound)
    ["/", false], // bare root — the "no mount" spelling (fix-ocr15)
    ["/ABC123", false], // case-sensitive in lockstep (fix-ocr19 #5 / fix-ocr17 #3)
    ["/a_b", false], // underscore is outside the alphabet
    ["/x!", false], // an injection-adjacent stray character
    ["label", false], // missing the leading slash
    ["/x/", false], // a trailing slash is not a label character
    ["/label ", false], // fix-ocr25 #4: whitespace is outside the alphabet —
    // the RAW value every face's regex must reject (两侧同判非法); the two
    // template faces trim BEFORE this check, so a whitespace-padded VALID
    // core still mounts as its trimmed self (pinned at module level above).
    ["", false], // the pattern itself rejects; callers treat empty as "no mount"
  ];

  test("nextjs-dev.ts, next.config.ts and lib/base-path.ts extract, and agree on every boundary", async () => {
    const serverSource = await readFile(
      join(hereDir, "../src/craft/nextjs-dev.ts"),
      "utf8",
    );
    const nextConfigSource = await read("next.config.ts");
    const basePathSource = await read("lib/base-path.ts");

    const serverPattern = extractLiteral(
      serverSource,
      /WEBAPP_BASE_PATH_PATTERN = (\/.+\/);/,
      "WEBAPP_BASE_PATH_PATTERN (nextjs-dev.ts)",
    );
    const templatePattern = extractLiteral(
      nextConfigSource,
      /configuredBasePath = (\/.+\/)\.test\(/,
      "the configuredBasePath whitelist (next.config.ts)",
    );
    const clientPattern = extractLiteral(
      basePathSource,
      /safeBasePath = (\/.+\/)\.test\(/,
      "the safeBasePath whitelist (lib/base-path.ts)",
    );

    for (const [value, accepted] of boundaryValues) {
      const verdicts = [
        ["server", serverPattern.test(value)],
        ["next.config.ts", templatePattern.test(value)],
        ["lib/base-path.ts", clientPattern.test(value)],
      ] as const;
      for (const [face, verdict] of verdicts) {
        expect(`${value} → ${face}: ${String(verdict)}`).toBe(
          `${value} → ${face}: ${String(accepted)}`,
        );
      }
    }
  });
});

describe("AGENTS.md teaches the two-shape mount contract", () => {
  test("dev form's /<label> prefix, the root production shape, and apiUrl() for every hand-built URL", async () => {
    const agents = await read("AGENTS.md");
    // The guidance has to name the mechanism, not just the fact: the dev form
    // mounts the app under an injected /<label> prefix (never hand-set), the
    // production form serves at the root, and every hand-built URL goes
    // through apiUrl() — the one code shape correct in both.
    expect(agents).toContain("/<label>");
    expect(agents).toContain("apiUrl()");
    expect(agents).toContain("automatically");
    // #413 AC3: the KNOWN bare-fetch behavior stays taught, not just the
    // apiUrl() remedy — Next prefixes assets but never a raw fetch(), which
    // resolves at the origin root and 404s beside the /<label> mount.
    expect(agents).toContain("a raw `fetch()`");
    expect(agents).toContain("404s beside");
    // The retired cwd foot-gun must stay gone from the guidance.
    expect(agents).not.toContain("resolveWebappBasePath");
  });
});
