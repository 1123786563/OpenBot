-- Enterprise identity connection grants, per plan 02 §7 T3-B step 3 (the identity-connection
-- permission contract). Executed by the MIGRATION OWNER only: the GRANTs below hand the NOLOGIN
-- capability role `ob_ent_identity` (server/ops/enterprise/roles.sql) exactly the table access the
-- standalone auth factory's own code performs, and nothing else. The enterprise API's identity
-- login (a member of ob_ent_identity, e.g. `ent_identity`) can then authenticate people without
-- holding a single privilege over the enterprise business tables.
--> statement-breakpoint
-- THE ENUMERATION, table by table, from the factory's actual statements (server/src/auth/index.ts)
-- and the adapters it configures — "identity table access" alone was never the contract:
--
--   users              drizzleAdapter (Better Auth core) selects FULL rows (findUserByEmail,
--                      findUserById, session create.before re-reading the email), INSERTs on first
--                      sign-in, UPDATEs profile refresh / emailVerified / lastSignedInAt
--                      (stampSignIn; updateUser calls in oauth2/link-account.mjs). DELETE is the
--                      delete-user route's, which the enterprise entry does not forward.
--                      → SELECT, INSERT, UPDATE (all columns: the adapter selects whole rows).
--   sessions           createSession (INSERT), findSession on every request (SELECT), expiry
--                      refresh (UPDATE), sign-out (DELETE).
--                      → SELECT, INSERT, UPDATE, DELETE.
--   accounts           linkAccount/createAccount (INSERT), updateAccount for token refresh under
--                      the existing encryptOAuthTokens mechanism (UPDATE), findAccount* (SELECT).
--                      The OAuth link/callback flow never deletes an account row (verified:
--                      better-auth@1.7.1 dist/oauth2/link-account.mjs uses linkAccount/
--                      updateAccount/createAccount only), and the unlink route is not forwarded.
--                      → SELECT, INSERT, UPDATE.
--   verifications      verification records of the enabled mechanisms: token INSERT, read on
--                      consumption, DELETE when consumed.
--                      → SELECT, INSERT, DELETE.
--   user_roles         seedRole/applyConfiguredAdmin (server/src/auth/roles.ts): setRole deletes
--                      the rows that should not be there and INSERTs the one that should, inside
--                      one transaction; the already-admin check SELECTs. Deployment roles never
--                      become tenant permissions (the enterprise guard reads memberships only).
--                      → SELECT, INSERT, DELETE. No UPDATE: setRole never updates.
--   enterprise_settings  createEnterpriseStore(database).settings() reads the whole table on every
--                      sign-in decision (ssoRequired). Writes belong to admin routes the
--                      enterprise entry does not mount.
--                      → SELECT.
--   revoked_access     the isRevoked callback (bootstrap composes it over this same connection)
--                      reads by lowercased email; writes belong to the directory offboard flow.
--                      → SELECT.
--
-- DELIBERATELY WITHHELD, with the reason each is safe to withhold:
--   sso_providers      the sso plugin's routes (/api/auth/sso/*) are excluded from the compiled
--                      auth-route profile, so no statement ever reaches this table on the
--                      enterprise entry; enterpriseStore.settings() reads enterprise_settings only.
--   scim_*             the SCIM plugin activates only under SCIM_BEARER_TOKEN, which the
--                      enterprise entry does not set; even if an operator set it, initialization
--                      only registers routes (no table access) and every /api/auth/scim route
--                      answers 404 through the allowlist.
--   enterprise tenancy/business tables (enterprise_tenants, enterprise_principals,
--   enterprise_memberships, enterprise_workspaces, enterprise_resources,
--   enterprise_resource_grants, enterprise_security_events, enterprise_identity_events)
--                      the identity connection has NO privilege here on purpose; directory and
--                      data connections hold their own restricted roles (0056_*.sql).
--   sequences          every id is application-generated text; there are no serial columns.
--> statement-breakpoint
-- The grants themselves. Table-level on purpose where the adapter selects full rows; per-statement
-- verbs above are the reason each verb is present or absent.
GRANT SELECT, INSERT, UPDATE ON users TO ob_ent_identity;
GRANT SELECT, INSERT, UPDATE, DELETE ON sessions TO ob_ent_identity;
GRANT SELECT, INSERT, UPDATE ON accounts TO ob_ent_identity;
GRANT SELECT, INSERT, DELETE ON verifications TO ob_ent_identity;
GRANT SELECT, INSERT, DELETE ON user_roles TO ob_ent_identity;
GRANT SELECT ON enterprise_settings TO ob_ent_identity;
GRANT SELECT ON revoked_access TO ob_ent_identity;
