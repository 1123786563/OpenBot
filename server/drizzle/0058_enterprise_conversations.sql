-- The channel table. A channel is one member's conversation with one bot: the owner is fixed at
-- creation (never drifts with later role changes), the bot is a same-tenant composite FK into the
-- ACL-owned resources (a channel cannot outlive the resource row it references — enforced, not
-- copied), and the thread id is generated by the server. The UNIQUE constraint is the creation
-- idempotency linearization point (spec §5); the index serves the owner's page scan.
CREATE TABLE enterprise_channels (
  tenant_id text NOT NULL,
  id text NOT NULL,
  owner_principal_id text NOT NULL,
  bot_resource_id text NOT NULL,
  thread_id text NOT NULL,
  client_request_id text NOT NULL,
  status text NOT NULL DEFAULT 'active',
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  archived_at timestamp with time zone,
  CONSTRAINT enterprise_channels_pk PRIMARY KEY (tenant_id, id),
  CONSTRAINT enterprise_channel_owner FOREIGN KEY (tenant_id, owner_principal_id)
    REFERENCES enterprise_memberships(tenant_id, principal_id),
  CONSTRAINT enterprise_channel_bot FOREIGN KEY (tenant_id, bot_resource_id)
    REFERENCES enterprise_resources(tenant_id, id),
  CONSTRAINT enterprise_channel_client_request UNIQUE (tenant_id, owner_principal_id, client_request_id),
  CONSTRAINT enterprise_channel_status CHECK (status in ('active','archived'))
);
