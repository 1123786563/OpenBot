    def doctor(self, runtime=False):
        if sys.version_info < (3, 10):
            raise SetupError('需要 Python 3.10 或更新版本')
        if not shutil.which('docker'):
            raise SetupError('缺少 Docker Engine。安装步骤见 deploy/README.md 的服务器准备。')
        info = json.loads(self.run(['docker', 'info', '--format', '{{json .}}'], capture=True, timeout=20))
        if info.get('OSType') != 'linux':
            raise SetupError('本安装流程需要 Linux Docker Engine')
        if info.get('MemTotal', 0) < 16 * 1024 ** 3:
            print('提示：Docker 可用内存不足 16 GiB，全套服务与镜像构建可能内存不足。')
        version = self.run(['docker', 'compose', 'version', '--short'], capture=True, timeout=20)
        numbers = tuple(map(int, re.findall(r'\d+', version)[:3]))
        if numbers < (2, 24, 4):
            raise SetupError('Docker Compose 至少需要 2.24.4，请安装或升级 docker-compose-plugin')
        if not Path('/var/run/docker.sock').exists() and sys.platform.startswith('linux'):
            raise SetupError('找不到 /var/run/docker.sock，Supervisor 需要访问该 Docker socket')
        free = shutil.disk_usage(ROOT).free // (1024 ** 3)
        if free < 30:
            print(f'提示：仓库所在磁盘仅剩 {free} GiB，完整镜像构建可能空间不足。')
        print(f'Docker 与 Compose 可用，仓库磁盘剩余 {free} GiB。')
        if runtime:
            self.require_config()
            self.validate_inputs(self.values)
            for component in COMPONENTS:
                self.compose(component, 'config', '--quiet', capture=True)
            print('所有平台组件配置有效。')
            self.check_ports()

    def check_ports(self):
        published = self.run(['docker', 'ps', '--format', '{{.Names}} {{.Ports}}'], capture=True)
        for port in [18001, 18080, 18082, 18888, 19999, 15173, 15080, 14318, 19000, 19001]:
            with socket.socket() as probe:
                try:
                    probe.bind(('127.0.0.1', port))
                except OSError:
                    owners = [line for line in published.splitlines() if f':{port}->' in line]
                    if not owners or not all(line.startswith('openbot-central-') for line in owners):
                        raise SetupError(f'端口 {port} 已被其他服务占用。先停止旧服务或改用一台全新服务器。')

