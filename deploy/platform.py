class SetupError(Exception):
    pass


def read_env(path):
    values = {}
    if not path.exists():
        return values
    for number, line in enumerate(path.read_text().splitlines(), 1):
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        match = re.fullmatch(r'([A-Z][A-Z0-9_]*)=(.*)', line)
        if not match:
            raise SetupError(f'{path}:{number} 不是 KEY=value 配置')
        key, value = match.groups()
        if value.startswith("'") and value.endswith("'"):
            value = value[1:-1].replace("\\'", "'")
        else:
            value = re.sub(r'\$\{([A-Z][A-Z0-9_]*)\}', lambda m: values.get(m[1], m[0]), value)
        values[key] = value
    return values


def write_env(path, values):
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    lines = []
    for key, value in values.items():
        if '\n' in str(value) or '\r' in str(value):
            raise SetupError(f'{key} 不能包含换行')
        escaped = str(value).replace("'", "\\'")
        lines.append(f"{key}='{escaped}'")
    temporary = path.with_name(path.name + '.tmp-' + secrets.token_hex(4))
    try:
        fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, 'w') as stream:
            stream.write('# Generated by deploy/deploy.sh. Keep this file private.\n' + '\n'.join(lines) + '\n')
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def basic(username, password):
    return 'Basic ' + base64.b64encode(f'{username}:{password}'.encode()).decode()


class Platform:
    def __init__(self, config_dir):
        self.directory = Path(config_dir).resolve()
        self.env_file = self.directory / '.env'
        self.user_file = self.directory / '.env.user'
        self.values = read_env(self.env_file)

    def redact(self, text):
        for key, value in self.values.items():
            if value and len(value) >= 8 and any(part in key for part in ['PASSWORD', 'SECRET', 'TOKEN', 'KEY', 'AUTH', 'DATABASE_URL']):
                text = text.replace(value, '[redacted]')
        return text

    def environment(self):
        env = {key: value for key, value in os.environ.items()
               if key in ['PATH', 'HOME', 'DOCKER_HOST', 'DOCKER_CONTEXT', 'DOCKER_CONFIG',
                          'HTTP_PROXY', 'HTTPS_PROXY', 'NO_PROXY', 'SSH_AUTH_SOCK']}
        env.update(CENTRAL_ENV_FILE=str(self.env_file),
                   OPENBOT_SERVER_ENV_FILE=str(self.directory / '.env.server'),
                   OPENBOT_AGENT_ENV_FILE=str(self.directory / '.env.agents'),
                   OPENBOT_WORKER_ENV_FILE=str(self.directory / '.env.worker'),
                   FLEXPRICE_ENV_FILE=str(self.directory / '.env.flexprice'),
                   OPENBOT_RUNTIME_LOG_DIR=str(self.directory / 'runtime-logs'))
        return env

    def run(self, command, *, capture=False, input=None, timeout=None):
        if not capture and input is None and timeout is None:
            tail = deque(maxlen=50)
            with subprocess.Popen(command, cwd=ROOT, env=self.environment(), text=True,
                                  stdout=subprocess.PIPE, stderr=subprocess.STDOUT, bufsize=1) as process:
                for line in process.stdout:
                    safe = self.redact(line)
                    tail.append(safe)
                    print(safe, end='', flush=True)
                code = process.wait()
            if code:
                raise SetupError(f'命令失败，退出码 {code}。\n' + ''.join(tail))
            return ''
        result = subprocess.run(command, cwd=ROOT, env=self.environment(), input=input,
                                text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                timeout=timeout)
        if not capture and result.stdout:
            print(self.redact(result.stdout), end='', flush=True)
        if result.returncode:
            detail = self.redact(result.stdout[-3500:] if result.stdout else '')
            raise SetupError(f'命令失败，退出码 {result.returncode}。\n{detail}')
        return result.stdout

    def compose(self, component, *args, **kwargs):
        if component not in [*COMPONENTS, 'flexprice']:
            raise SetupError(f'未知组件 {component}，可选：{", ".join(COMPONENTS)}')
        return self.run(['bash', str(ROOT / 'deploy/compose.sh'), '--central', component, *args], **kwargs)

    def require_config(self):
        if not self.env_file.exists():
            raise SetupError('还没有安装配置。先运行 ./deploy/deploy.sh init')

    @contextmanager
    def lock(self):
        import fcntl
        self.directory.mkdir(parents=True, exist_ok=True, mode=0o700)
        with (self.directory / '.install.lock').open('w') as stream:
            try:
                fcntl.flock(stream, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError:
                raise SetupError('已有安装或配置操作在运行。等待该操作结束后再重试。') from None
            yield

