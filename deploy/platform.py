    def wait_http(self, url, *, authorization=None, seconds=300):
        end = time.monotonic() + seconds
        while time.monotonic() < end:
            try:
                request = urllib.request.Request(url, headers={'Authorization': authorization} if authorization else {})
                with urllib.request.urlopen(request, timeout=5) as response:
                    if response.status < 400:
                        return
            except (OSError, urllib.error.HTTPError):
                pass
            time.sleep(2)
        raise SetupError(f'{url} 未在 {seconds} 秒内就绪。运行 ./deploy/deploy.sh logs 对应组件')

    def request(self, url, authorization, method='GET', payload=None):
        request = urllib.request.Request(url, headers={'Authorization': authorization, 'Content-Type': 'application/json'},
                                         data=json.dumps(payload).encode() if payload is not None else None, method=method)
        try:
            with urllib.request.urlopen(request, timeout=15) as response:
                body = response.read()
                return response.status, json.loads(body) if body else {}
        except urllib.error.HTTPError as error:
            return error.code, {}

    def bootstrap_observe(self):
        v = self.values
        origin = f"http://127.0.0.1:{v['OPENOBSERVE_PORT']}/api/default"
        auth = basic(v['OPENOBSERVE_ROOT_EMAIL'], v['OPENOBSERVE_ROOT_PASSWORD'])
        email = v['OPENOBSERVE_COLLECTOR_EMAIL']
        code, users = self.request(origin + '/users', auth)
        if code != 200:
            raise SetupError(f'OpenObserve 用户列表不可用（HTTP {code}）')
        if not any(user.get('email') == email for user in users.get('data', [])):
            code, _ = self.request(origin + '/users', auth, 'POST',
                                   {'email': email, 'password': v['OPENOBSERVE_COLLECTOR_PASSWORD'],
                                    'first_name': 'OpenBot', 'last_name': 'Collector', 'role': 'editor'})
        if code not in [200, 201]:
            raise SetupError(f'OpenObserve 采集账号初始化失败（HTTP {code}），查看 deploy/docs/troubleshooting.md')
        collector = basic(email, v['OPENOBSERVE_COLLECTOR_PASSWORD'])
        code, _ = self.request(origin + '/streams', collector)
        if code != 200:
            raise SetupError(f'OpenObserve 采集凭据校验失败（HTTP {code}），原账号未被覆盖')
        v.update(OPENOBSERVE_RUNTIME_AUTHORIZATION=collector, OPENOBSERVE_AUDIT_AUTHORIZATION=collector)
        self.save()

    def skill_reader(self):
        end = time.monotonic() + 180
        while time.monotonic() < end:
            result = self.compose('infrastructure', 'exec', '-T', 'postgres', 'psql', '-U', 'postgres', '-d', 'bifrost',
                                  '-XAt', '-c', "SELECT to_regclass('public.skill_versions') IS NOT NULL", capture=True)
            if result.strip() == 't':
                break
            time.sleep(2)
        else:
            raise SetupError('Bifrost 未初始化技能表。检查 ./deploy/deploy.sh logs bifrost')
        sql = "\\set reader_password '" + self.values['SKILL_READER_DB_PASSWORD'] + "'\n"
        sql += "SELECT format('CREATE ROLE openbot_skill_reader LOGIN PASSWORD %L', :'reader_password') "
        sql += "WHERE NOT EXISTS (SELECT FROM pg_roles WHERE rolname='openbot_skill_reader') \\gexec\nSET ROLE bifrost;\n"
        sql += (ROOT / 'deploy/bifrost/skill-market-reader.sql').read_text()
        self.compose('infrastructure', 'exec', '-T', 'postgres', 'psql', '-U', 'postgres', '-d', 'bifrost',
                     '-X', '-v', 'ON_ERROR_STOP=1', input=sql, capture=True)

    def up(self):
        self.require_config()
        self.doctor(runtime=True)
        for key in ['OPENBOT_IMAGE', 'BOT_IMAGE', 'LANGGRAPH_IMAGE', 'COMPUTER_IMAGE', 'SUPERVISOR_IMAGE']:
            try:
                self.run(['docker', 'image', 'inspect', self.values[key]], capture=True, timeout=15)
            except SetupError:
                raise SetupError('缺少本地平台镜像。先运行 ./deploy/deploy.sh build，再运行 up') from None
        with self.lock():
            steps = [
                ('启动 PostgreSQL 与 MySQL', lambda: self.compose('infrastructure', 'up', '-d', '--wait', '--wait-timeout', '300', 'postgres', 'mysql')),
                ('创建专用数据库与向量扩展', lambda: self.compose('infrastructure', 'run', '--rm', 'postgres-init')),
                ('启动 Redis Sentinel、RustFS 与 ClickHouse', lambda: self.compose('infrastructure', 'up', '-d', '--wait', '--wait-timeout', '300', *STORAGE[2:])),
                ('初始化 RustFS bucket 与专用访问密钥', self.bootstrap_rustfs),
                ('启动并初始化 Infisical 管理员', self.bootstrap_infisical),
                ('启动 Hindsight 与 Opik', self.start_memory_tracing),
                ('启动 Bifrost 并创建技能目录只读账号', self.start_bifrost),
                ('启动 OpenObserve 并配置独立采集账号', self.start_observe),
                ('初始化 SPIRE 并启动 Agent 与浏览器', self.start_agents),
                ('迁移业务数据库并启动 OpenBot API 与 Worker', lambda: self.compose('openbot', 'up', '-d', '--wait', '--wait-timeout', '300')),
            ]
            for index, (title, action) in enumerate(steps, 1):
                print(f'\n[{index}/{len(steps)}] {title}', flush=True)
                action()
        self.check()
        print(f'\n平台已启动。访问 http://localhost:{self.values["OPENBOT_PORT"]}')
        print('远程服务器的 SSH 隧道命令见 deploy/README.md。管理员凭据使用 credentials 命令查看。')

