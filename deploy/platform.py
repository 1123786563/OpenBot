    @staticmethod
    def validate_inputs(values, require_model=True):
        if not re.fullmatch(r'[^\s@]+@[^\s@]+\.[^\s@]+', values.get('PLATFORM_ADMIN_EMAIL', '')):
            raise SetupError('管理员邮箱格式不正确')
        url = urllib.parse.urlparse(values.get('OPENAI_BASE_URL', ''))
        if url.scheme not in ['http', 'https'] or not url.hostname or url.username or url.password:
            raise SetupError('模型 API 地址必须是无内嵌密码的 http(s) URL')
        if require_model and (not values.get('OPENAI_API_KEY') or not values.get('BOT_MODEL')):
            raise SetupError('缺少模型 API key 或模型名称。运行 ./deploy/deploy.sh configure')

