#!/usr/bin/env bash
# Generate docker/lago/.env — the secrets and one-shot seed values for the Lago services in
# docker-compose.yml. Local-only, never commit (`.env` is gitignored).
#
# Usage: ./docker/lago/init-env.sh
#
# Everything random is generated fresh; nothing hard-coded here is a secret. LAGO_RSA_PRIVATE_KEY
# is the key Lago signs webhook JWTs with — the matching public key is what OpenBot's
# LAGO_WEBHOOK_PUBLIC_KEY expects (base64 of the PEM, which OpenBot unwraps).
#
# The LAGO_CREATE_ORG block is a one-shot seed: Lago's migrate container mints the operator
# account and the organization API key with exactly these values on the first `up` against an
# empty schema. Delete the four LAGO_ORG_* lines (and LAGO_CREATE_ORG) after that first boot to
# keep the throwaway values out of a file the stack keeps reading.
set -euo pipefail

ENV_FILE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/.env"

if [[ -e "$ENV_FILE" ]]; then
  echo "init-env: refusing to overwrite existing $ENV_FILE (delete it first to regenerate)" >&2
  exit 1
fi

random_secret() { python3 -c "import secrets; print(secrets.token_urlsafe($1))"; }
random_hex() { python3 -c "import secrets; print(secrets.token_hex($1))"; }

rsa_key="$(openssl genrsa 2048 2>/dev/null | openssl base64 -A)"
[[ -n "$rsa_key" ]] || { echo "init-env: openssl failed to generate the RSA key" >&2; exit 1; }

umask 077
{
  echo "# Generated by docker/lago/init-env.sh -- local secrets, never commit."
  echo "SECRET_KEY_BASE=$(random_hex 32)"
  echo "LAGO_ENCRYPTION_PRIMARY_KEY=$(random_secret 32)"
  echo "LAGO_ENCRYPTION_DETERMINISTIC_KEY=$(random_secret 32)"
  echo "LAGO_ENCRYPTION_KEY_DERIVATION_SALT=$(random_secret 16)"
  echo "LAGO_RSA_PRIVATE_KEY=\"${rsa_key}\""
  echo ""
  echo "# One-shot organization seed, consumed on the first boot against an empty schema."
  echo "LAGO_CREATE_ORG=true"
  echo "LAGO_ORG_USER_EMAIL=ops@openbot.local"
  echo "LAGO_ORG_USER_PASSWORD=$(random_secret 18)"
  echo "LAGO_ORG_NAME=OpenBot"
  echo "LAGO_ORG_API_KEY=$(random_secret 32)"
} > "$ENV_FILE"

openssl rsa -in <(printf '%s' "$rsa_key" | openssl base64 -d -A) -pubout 2>/dev/null \
  | openssl base64 -A > "${ENV_FILE}.webhook-public-key.b64"
chmod 600 "${ENV_FILE}.webhook-public-key.b64"

echo "wrote $ENV_FILE (mode 600) and ${ENV_FILE}.webhook-public-key.b64"
echo "After first boot: LAGO_API_KEY = the LAGO_ORG_API_KEY above; LAGO_WEBHOOK_PUBLIC_KEY = the .b64 file's contents."
